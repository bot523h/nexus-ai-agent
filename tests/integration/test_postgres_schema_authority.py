"""Schema authority on a real PostgreSQL (CI ``migrate-postgres`` job).

Closes two audit findings on the deployment backend, not just on SQLite:

* **A-19** — ``alembic check`` on a database that also holds LangGraph's
  checkpoint tables used to report ``remove_table`` for every foreign table,
  and ``--autogenerate`` proposed dropping them.  With
  ``migration_metadata.include_object`` the gate is clean *and* still catches
  drift on an owned table.
* **conversation_history adoption** — a deployment where the old
  ``ConversationStore`` already created the table is upgraded in place: the
  rows survive, the legacy index name is kept, and the revision can be rolled
  back and re-applied (``alembic downgrade -1`` → ``nexus migrate``).

Runs only when ``NEXUS_DATABASE_URL`` points at a disposable PostgreSQL; the
test rewinds the shared database one revision and brings it back to head.
"""

from __future__ import annotations

import os
from pathlib import Path

import psycopg
import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from nexus_ai_agent.features.conversation_store import ConversationStore

PG_URL = os.getenv("NEXUS_DATABASE_URL")
requires_pg = pytest.mark.skipif(not PG_URL, reason="requires PostgreSQL")

REPO = Path(__file__).resolve().parents[2]
PREVIOUS_HEAD = "b5d8e2f4a917"
HEAD = "c7a1e5d2b9f3"

# What the pre-closeout ConversationStore emitted on PostgreSQL (``create_all``
# of its private MetaData) — the shape an existing deployment carries.
_LEGACY_DDL = (
    "CREATE TABLE conversation_history ("
    "id SERIAL NOT NULL, conv_id VARCHAR NOT NULL, role VARCHAR NOT NULL, "
    "parts_json TEXT NOT NULL, created_at TIMESTAMP WITHOUT TIME ZONE "
    "DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id))",
    "CREATE INDEX ix_conv_history_conv_id ON conversation_history (conv_id)",
)


def _config() -> Config:
    config = Config(str(REPO / "alembic.ini"))
    config.set_main_option("script_location", str(REPO / "migrations"))
    return config


def _version(conn: psycopg.Connection) -> str:
    row = conn.execute("SELECT version_num FROM alembic_version").fetchone()
    assert row is not None
    return str(row[0])


@requires_pg
def test_legacy_conversation_history_is_adopted_in_place_and_the_revision_is_repeatable() -> None:
    assert PG_URL is not None
    config = _config()
    command.upgrade(config, "head")  # CI already ran `nexus migrate`; idempotent
    command.downgrade(config, PREVIOUS_HEAD)  # the deployment before the closeout

    with psycopg.connect(PG_URL, autocommit=True) as conn:
        assert _version(conn) == PREVIOUS_HEAD
        for statement in _LEGACY_DDL:
            conn.execute(statement)  # the old store's runtime create_all
        conn.execute(
            "INSERT INTO conversation_history (conv_id, role, parts_json) VALUES "
            "('tg:5000000001', 'user', '[{\"text\": \"before the closeout\"}]')"
        )

    command.upgrade(config, "head")  # == `nexus migrate` on the deployment

    with psycopg.connect(PG_URL, autocommit=True) as conn:
        assert _version(conn) == HEAD
        rows = conn.execute(
            "SELECT conv_id, role, parts_json FROM conversation_history ORDER BY id"
        ).fetchall()
        assert rows == [("tg:5000000001", "user", '[{"text": "before the closeout"}]')]
        indexes = {
            r[0]
            for r in conn.execute(
                "SELECT indexname FROM pg_indexes WHERE tablename = 'conversation_history'"
            )
        }
        assert "ix_conv_history_conv_id" in indexes

    # The store reads the adopted rows through the production engine …
    store = ConversationStore(db_path=None)
    assert store.get_history("tg:5000000001") == [
        {"role": "user", "parts": [{"text": "before the closeout"}]}
    ]
    # … and the revision is reversible/repeatable (deployment rollback drill).
    command.downgrade(config, "-1")
    with psycopg.connect(PG_URL, autocommit=True) as conn:
        assert _version(conn) == PREVIOUS_HEAD
        present = conn.execute("SELECT to_regclass('public.conversation_history')").fetchone()
        assert present == (None,)
    command.upgrade(config, "head")
    with psycopg.connect(PG_URL, autocommit=True) as conn:
        assert _version(conn) == HEAD


@requires_pg
def test_alembic_check_is_clean_next_to_langgraph_tables_and_still_detects_owned_drift() -> None:
    """A-19 on the deployment backend."""
    assert PG_URL is not None
    from langgraph.checkpoint.postgres import PostgresSaver

    config = _config()
    command.upgrade(config, "head")
    with psycopg.connect(PG_URL, autocommit=True) as conn:
        PostgresSaver(conn).setup()  # the foreign tables every deployment carries
        foreign = {
            r[0]
            for r in conn.execute(
                "SELECT tablename FROM pg_tables WHERE schemaname = 'public' "
                "AND tablename LIKE 'checkpoint%'"
            )
        }
    assert {"checkpoints", "checkpoint_blobs", "checkpoint_writes"} <= foreign

    command.check(config)  # was: AutogenerateDiffsDetected (remove_table × 4+)

    with psycopg.connect(PG_URL, autocommit=True) as conn:
        conn.execute("ALTER TABLE userxp ADD COLUMN stray_column INTEGER")
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(config)
    finally:
        with psycopg.connect(PG_URL, autocommit=True) as conn:
            conn.execute("ALTER TABLE userxp DROP COLUMN stray_column")
    command.check(config)
