"""Hybrid CAS resource-pack delivery: remote delta downloads + local DNA seed hydration.

Three tiers (``core`` — mandatory, ``standard``, ``cinema_hd``) are described
by signed manifests over an RFC 6962 Merkle tree.  On studio login the
:class:`ResourcePackSyncManager` decides, per file, whether to reuse a blob
already in the local content-addressed store, bake it on the device from a
few-byte seed recipe, or download it with resumable HTTP ``Range`` requests —
and activates the result atomically, only after full verification.
"""

